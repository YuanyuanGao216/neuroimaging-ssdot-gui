function summary = summarizeRecording(name, prepared, result, atlas, coordinates, hemisphere, parcels, hands, folder)
    %SUMMARIZERECORDING Reuse audited numerical statistics, preserving units/indexing.
    if ~isfolder(folder)
        mkdir(folder);
    end

    sensitivity = prepared.sensitivity;
    temporal = prepared.model.temporalBasis;
    mesh = atlas.fwmodel.mesh;
    modeled = false(size(mesh.vertices, 1), 1);
    modeled(sensitivity.M.mask_brain) = true;
    area = ssdot.validation.vertexAreas(mesh);

    stats = ssdot.validation.mapStatistics(result, mesh.vertices, coordinates, hemisphere, modeled, ...
        temporal.conditionNames);
    [relationships, laterality, cbr, rois, hrf] = ssdot.validation.regionalAnalysis(result, temporal, ...
        sensitivity.M, mesh.vertices, hemisphere, modeled, area);
    factors = ssdot.recon.factorDesign(prepared.model, 'cpu');
    [fit, channelFit, components, optical, events] = ssdot.validation.opticalAnalysis(result, ...
        prepared.recording, prepared.observations, factors, result.coefficients(:), sensitivity, ...
        prepared.probe, hemisphere, modeled, temporal);

    writetable(stats, fullfile(folder, 'map-statistics.csv'));
    writetable(relationships, fullfile(folder, 'hbo-hbr.csv'));
    writetable(laterality, fullfile(folder, 'laterality.csv'));
    writetable(cbr, fullfile(folder, 'exploratory-cbr.csv'));
    writetable(hrf, fullfile(folder, 'fitted-hrf.csv'));
    writetable(fit, fullfile(folder, 'optical-fit.csv'));
    writetable(channelFit, fullfile(folder, 'measurement-residuals.csv'));
    writetable(components, fullfile(folder, 'components.csv'));
    writetable(events, fullfile(folder, 'event-related-optical.csv'));

    inference = ssdot.validation.anatomicalMetrics(result, coordinates, hemisphere, modeled, parcels, hands, ...
        temporal.conditionNames);
    writetable(inference, fullfile(folder, 'anatomical-inference.csv'));

    temporalProvenance = struct('mode', temporal.temporalMode, 'gammaParameters', temporal.gammaParameters, ...
        'eventConvention', temporal.eventConvention, 'temporalRange', temporal.temporalRange, ...
        'implementationVersion', temporal.temporalImplementationVersion, 'eventMetadata', {temporal.eventMetadata});
    payload = struct('hbo', result.hbo, 'hbr', result.hbr, 'coefficients', result.coefficients, ...
        'hboHrf', cat(3, result.concentrations.intensity_HbO{:}), ...
        'hbrHrf', cat(3, result.concentrations.intensity_HbR{:}), ...
        'hrfTime', temporal.time, 'conditionNames', {temporal.conditionNames}, 'mask', sensitivity.M.mask_brain, ...
        'vertices', mesh.vertices, 'coordinates', coordinates, 'hemisphere', hemisphere, 'parcels', parcels, ...
        'faces', mesh.faces, 'solverDiagnostics', result.solverDiagnostics, 'config', prepared.config, ...
        'temporalBasis', temporal, 'temporalProvenance', temporalProvenance, 'optical', optical, 'rois', rois);
    payload = ssdot.validation.portableData(payload);
    save(fullfile(folder, 'numerical-results.mat'), '-struct', 'payload', '-v7');


    summary = struct('name', name, 'folder', folder, 'config', prepared.config, ...
        'conditions', {temporal.conditionNames}, 'temporal', temporalProvenance, ...
        'hboMinM', min(result.hbo, [], 'all'), 'hboMaxM', max(result.hbo, [], 'all'), ...
        'hbrMinM', min(result.hbr, [], 'all'), 'hbrMaxM', max(result.hbr, [], 'all'), ...
        'nanInf', sum(~isfinite([result.hbo(:); result.hbr(:)])), ...
        'modeledVertices', numel(sensitivity.M.mask_brain), 'brainKernels', size(prepared.centers.brain, 1), ...
        'scalpKernels', size(prepared.centers.scalp, 1), 'solver', result.solverDiagnostics, ...
        'fit', table2struct(fit), 'relationships', table2struct(relationships), ...
        'components', table2struct(components), 'laterality', table2struct(laterality), ...
        'inference', table2struct(inference));
    ssdot.validation.writeJson(fullfile(folder, 'summary.json'), summary);
end
