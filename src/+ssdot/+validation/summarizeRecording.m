function summary=summarizeRecording(name,prepared,result,atlas,coordinates,hemisphere,parcels,hands,folder)
    %SUMMARIZERECORDING Reuse audited numerical statistics, preserving units/indexing.
    if ~isfolder(folder), mkdir(folder); end
    S=prepared.sensitivity; T=prepared.model.temporalBasis; mesh=atlas.fwmodel.mesh;
    modeled=false(size(mesh.vertices,1),1); modeled(S.M.mask_brain)=true;
    area=ssdot.validation.vertexAreas(mesh);
    stats=ssdot.validation.mapStatistics(result,mesh.vertices,coordinates,hemisphere,modeled,T.conditionNames);
    [relationships,laterality,cbr,rois,hrf]=ssdot.validation.regionalAnalysis(result,T,S.M,mesh.vertices,hemisphere,modeled,area);
    factors=ssdot.recon.factorDesign(prepared.model,'cpu');
    [fit,channelFit,components,optical,events]=ssdot.validation.opticalAnalysis(result,prepared.recording,prepared.observations, ...
        factors,result.coefficients(:),S,prepared.probe,hemisphere,modeled,T);
    writetable(stats,fullfile(folder,'map-statistics.csv')); writetable(relationships,fullfile(folder,'hbo-hbr.csv'));
    writetable(laterality,fullfile(folder,'laterality.csv')); writetable(cbr,fullfile(folder,'exploratory-cbr.csv'));
    writetable(hrf,fullfile(folder,'fitted-hrf.csv')); writetable(fit,fullfile(folder,'optical-fit.csv'));
    writetable(channelFit,fullfile(folder,'measurement-residuals.csv')); writetable(components,fullfile(folder,'components.csv'));
    writetable(events,fullfile(folder,'event-related-optical.csv'));
    inference=ssdot.validation.anatomicalMetrics(result,coordinates,hemisphere,modeled,parcels,hands,T.conditionNames);
    writetable(inference,fullfile(folder,'anatomical-inference.csv'));
    temporalProvenance=struct('mode',T.temporalMode,'gammaParameters',T.gammaParameters, ...
        'eventConvention',T.eventConvention,'temporalRange',T.temporalRange, ...
        'implementationVersion',T.temporalImplementationVersion,'eventMetadata',{T.eventMetadata});
    payload=struct('hbo',result.hbo,'hbr',result.hbr,'coefficients',result.coefficients, ...
        'hboHrf',cat(3,result.concentrations.intensity_HbO{:}),'hbrHrf',cat(3,result.concentrations.intensity_HbR{:}), ...
        'hrfTime',T.time,'conditionNames',{T.conditionNames},'mask',S.M.mask_brain,'vertices',mesh.vertices, ...
        'coordinates',coordinates,'hemisphere',hemisphere,'parcels',parcels,'faces',mesh.faces, ...
        'solverDiagnostics',result.solverDiagnostics,'config',prepared.config,'temporalBasis',T, ...
        'temporalProvenance',temporalProvenance,'optical',optical,'rois',rois);
    payload=ssdot.validation.portableData(payload); save(fullfile(folder,'numerical-results.mat'),'-struct','payload','-v7');
    summary=struct('name',name,'folder',folder,'config',prepared.config,'conditions',{T.conditionNames}, ...
        'temporal',temporalProvenance, ...
        'hboMinM',min(result.hbo,[],'all'),'hboMaxM',max(result.hbo,[],'all'), ...
        'hbrMinM',min(result.hbr,[],'all'),'hbrMaxM',max(result.hbr,[],'all'), ...
        'nanInf',sum(~isfinite([result.hbo(:);result.hbr(:)])), ...
        'modeledVertices',numel(S.M.mask_brain),'brainKernels',size(prepared.centers.brain,1), ...
        'scalpKernels',size(prepared.centers.scalp,1),'solver',result.solverDiagnostics, ...
        'fit',table2struct(fit),'relationships',table2struct(relationships),'components',table2struct(components), ...
        'laterality',table2struct(laterality),'inference',table2struct(inference));
    ssdot.validation.writeJson(fullfile(folder,'summary.json'),summary);
end
