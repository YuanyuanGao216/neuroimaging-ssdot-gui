function writeStudyReport(study)
    %WRITESTUDYREPORT Separate numerical, recovery and physiological evidence.
    % Sections are appended to one HTML string by the nested writers below.
    folder = study.options.outputFolder;
    html = "";
    heading("Scientific validation of SS-DOT", 1);
    paragraph("Execution: " + study.state + ". Elapsed wall time: " + compose('%.1f', study.elapsedSeconds) + ...
        " s. Completed " + study.completedUtc + ". No overall validation score is calculated.");
    if isfield(study, 'integrationHistory')
        paragraph(string(study.integrationHistory));
    end
    writeConclusions();
    writeEvidenceInventory();
    writeSt001Section();
    writeGroundTruthSection();
    writeBenchmarkSection();
    writePublicDataSection();
    writeIssuesAndLimits();
    appendFigures();
    writeText(fullfile(folder, 'report.html'), htmlDocument(html));

    function writeConclusions()
        heading("Conclusions and unexpected findings", 2);
        paragraph("A finite reconstruction and a small inverse-equation residual establish numerical " + ...
            "consistency, not correct cortical attribution. Read ground-truth amplitude/localization results " + ...
            "and refitted brain contribution before interpreting a colored surface as task activation. Baseline " + ...
            "equations, resolution, double precision and regularization are unchanged; sensitivity arms are " + ...
            "explicitly labeled experiments.");
        if ~isempty(study.synthetic)
            results = study.synthetic.results;
            positive = ~[results.negativeControl];
            good = [results.criteriaPassed];
            paragraph("Known-source tests: " + sum(good & positive) + " of " + sum(positive) + ...
                " positive-source metric rows meet the predeclared recovery criteria. Negative controls: " + ...
                sum(good & ~positive) + " of " + sum(~positive) + " rows meet the absolute false-positive " + ...
                "criterion. These are different questions and are not merged into a score.");
            if any(~good & positive)
                paragraph("RECONSTRUCTION ACCURACY IS NOT ESTABLISHED: at least one controlled positive-source " + ...
                    "recovery criterion failed. Low false-positive rates cannot compensate for failure to " + ...
                    "recover a known signal. No parameter was selected to make these tests pass.");
            end
        end
        paragraph("Physiological validity remains uncertain unless supported by known task identity, anatomy " + ...
            "and independent evidence. Human recordings do not supply voxel-wise ground truth; agreement with " + ...
            "another reconstruction method is not proof of accuracy.");
        paragraph("Temporal compatibility is reported separately from physiological accuracy. Each recording " + ...
            "summary and MAT export records the temporal mode, gamma parameters, event convention, temporal " + ...
            "range, implementation version and original event metadata. The professorOriginal mode uses onset " + ...
            "impulses and configured-T gamma smoothing; durationBased retains the previous " + ...
            "event-duration-spread alternative. A match to the pinned temporal construction does not resolve " + ...
            "known-source amplitude/localization failures or establish physiological validity.");
    end

    function writeEvidenceInventory()
        heading("Evidence inventory", 2);
        rows = {};
        for k = 1:numel(study.records)
            rows(end + 1, :) = {study.records{k}.name, "Raw + stored Homer OD + registered template model", ...
                "Numerical/fit diagnostics", "Unknown hand labels; no cortical ground truth"};
        end
        if ~isempty(study.synthetic)
            rows(end + 1, :) = {"Controlled synthetic sources", "Exact injected brain/scalp signals and locations", ...
                "Recovery/false positives", "Model mismatch cases are stress tests, not human physiology"};
        end
        if ~isempty(study.benchmark)
            rows(end + 1, :) = {"Cedalion motor-task DOT", ...
                "Raw recording + author-matched head/sensitivity + task mapping", ...
                "Independent geometry/method benchmark", "Author registration; no subject-specific activation truth"};
        end
        if ~isempty(study.publicData)
            rows(end + 1, :) = {"Published Gao ds007420", "Checksum-verified raw task/rest/motion recordings", ...
                "Input/preprocessing compatibility", "Matched registered DOT models still absent"};
        end
        tableBlock({'Dataset', 'Available evidence', 'What it tests', 'Limits'}, rows);
    end

    function writeSt001Section()
        heading("ST001 across recordings", 2);
        [overview, ablations, holdout, arms] = recordTables(study.records);
        for k = 1:numel(study.records)
            record = study.records{k};
            paragraph("Detailed arrays, per-hemisphere percentiles/extrema, coordinate conventions, ROI " + ...
                "relationships, time courses and residuals: [" + record.name + "](" + ...
                string(java.io.File(char(record.folder)).getName()) + "/summary.json).");
        end

        tableBlock({'Recording', 'max |HbO| (uM)', 'max |HbR| (uM)', 'Spatial HbO/HbR r by condition', ...
            'Within-channel R2 (760/850)', 'Brain component norm % (sum, not variance)', 'NaN/Inf maps', ...
            'Clipped modeled values'}, overview);
        paragraph("Component norms overlap and can cancel; summed percentages are not additive explained " + ...
            "variance. Clipping counts cover both conditions/chromophores at the GUI fixed range +/-1e-9 M, not " + ...
            "altered data. ST001 condition names remain literal 1 and 2 unless independently documented. " + ...
            "Native-template coordinates do not establish MNI/M1 localization. Full and sensitivity-masked " + ...
            "statistics are exported separately so zero padding cannot dilute the summaries.");

        tableBlock({'Recording', 'Full SSE', 'Refitted no-brain SSE', 'Brain-associated SSE reduction %', ...
            'Regularized image condition bound'}, ablations);
        paragraph("The no-brain/no-scalp fits refit all retained image and nuisance coefficients, keeping the " + ...
            "full model's absolute image penalty. Nuisance-only fits are also refitted. These controlled nested " + ...
            "comparisons differ from simply subtracting a saved component. A small SSE difference is not a " + ...
            "task-significance test.");

        tableBlock({'Recording', 'Held-out model', 'nm', 'Test RMSE OD', 'R2 vs training channel mean', ...
            'Independent long targets'}, holdout);
        paragraph("Held-out fits use every third 60-s block as test data, with a 20-s exclusion buffer for " + ...
            "training. Only channels outside the short-channel mean are scored to prevent direct target leakage " + ...
            "into SS predictors. Stored preprocessing may cross fold boundaries and residuals are " + ...
            "autocorrelated, so this is a buffered predictive diagnostic, not a fully independent preprocessing " + ...
            "cross-validation or a p-value.");

        tableBlock({'Recording', 'Alpha', 'Baseline', 'Image penalty', 'max |HbO| uM', 'max |HbR| uM'}, arms);
        comparisons = referenceComparisonRows(study.records);
        if ~isempty(comparisons)
            paragraph("The separate NeuroDOT comparison refits sequential SS+drift on the same stored OD, then " + ...
                "applies the original NeuroDOT Tikhonov/spectroscopy routines with the same forward " + ...
                "sensitivity, channels, masks and event windows. It uses a different inverse, temporal model " + ...
                "and regularization; it is neither the professor's full pipeline nor a gold standard.");
            tableBlock({'Recording', 'Condition', 'Hb', 'Side', 'SS-DOT mean uM', 'NeuroDOT mean uM', 'Spatial r'}, ...
                comparisons);
        end
        paragraph("All arms retain full Research spatial resolution. The baseline alpha remains 0.01. No best " + ...
            "alpha is selected. Model-scales.csv and conditioning.json record optical-block spectral scales, " + ...
            "image nullity bounds and nuisance temporal conditioning. A well-conditioned penalized inverse does " + ...
            "not make the unregularized cortical attribution identifiable.");
    end

    function writeGroundTruthSection()
        heading("Known-ground-truth experiments", 2);
        paragraph("One control uses an exactly matched brain spatial/temporal basis. Its measured short-channel " + ...
            "regressor still contains any injected brain signal, so the complete forward experiment is not a " + ...
            "perfect inverse-crime control. Other cases use independently constructed top-hat patches, an " + ...
            "alternative covered location, bilateral sources, a double-gamma response with HbR delay, 3-mm " + ...
            "sensitivity displacement with 5% gains, opposite-sign contrasts and brain-free controls with " + ...
            "superficial physiology/drift. Superficial concentration is selected to give a prespecified 0.02 or " + ...
            "0.06 OD RMS, with its actual model-implied concentration retained per case. Recorded-residual " + ...
            "Fourier-phase surrogates preserve optical auto/cross spectra; they are not verified resting " + ...
            "recordings. The same full Research model reconstructs every case.");
        paragraph("Predeclared positive-source criteria: ROI mean amplitude ratio " + ...
            strjoin(string(study.options.amplitudeTolerance), " to ") + ...
            ", localization error <= " + study.options.localizationToleranceMm + " mm, spatial r >= " + ...
            study.options.spatialCorrelationThreshold + ", and false-positive fraction <= " + ...
            study.options.falsePositiveFractionTolerance + " at |concentration| > " + ...
            study.options.falsePositiveThresholdM * 1e6 + " uM. Negative controls use only the absolute " + ...
            "false-positive criterion. These are disclosed study acceptance criteria, not universal or " + ...
            "paper-derived thresholds. Localization is undefined when no estimated peak exceeds 1 pM; undefined " + ...
            "errors are excluded from medians and do not pass the recovery criterion.");
        if isempty(study.synthetic)
            return;
        end

        tableBlock({'Scenario', 'Metric rows', 'Criteria met', 'Median amplitude ratio', 'Median location error mm', ...
            'Median spatial r', 'Max false-positive fraction'}, scenarioRows(study.synthetic.results));
        paragraph("[All synthetic metrics](synthetic/ground-truth-metrics.csv), per-case MAT arrays and " + ...
            "[protocol](synthetic/protocol.mat) retain truth maps, configurations and seeds. Maps compare both " + ...
            "chromophores at the app's fixed HbO-peak sample; independent true HRF curves are retained so " + ...
            "timing mismatch is not silently peak-aligned. Known-source ROI CBR uses the signed paper formula " + ...
            "with independently known source masks; it is not a replication of the paper's original masks or " + ...
            "participant ensemble.");
        for k = 1:numel(study.synthetic.failures)
            failure = study.synthetic.failures{k};
            paragraph("SYNTHETIC CASE NOT COMPLETED - " + failure.scenario + ": " + failure.identifier + ...
                " - " + failure.message);
        end
    end

    function writeBenchmarkSection()
        heading("Independent Cedalion / NeuroDOT benchmark", 2);
        if isempty(study.benchmark)
            paragraph("This section was not completed. See the section-specific failures below; no incompatible " + ...
                "model was forced and no physiological validation is claimed.");
            return;
        end
        benchmark = study.benchmark;
        paragraph("[Author tutorial](https://github.com/ibs-lab/cedalion/blob/" + ...
            "c463978a799e843dfde0631500336948cbdd63ee/examples/tutorial/5_image_reconstruction.ipynb) " + ...
            "supplies descriptive hand/condition labels. The 26.5.1 recording, native meshes, sensitivity " + ...
            "columns and parcel/MNI correspondences are checksum-pinned. Channel identities and wavelengths are " + ...
            "checked exactly; registration is author-supplied and is not re-estimated. This model is never " + ...
            "substituted for ST001 or Gao's public probe.");
        paragraph("Both methods use the same channel set, geometry and derived OD: natural-log conversion and " + ...
            "fourth-order zero-phase 0.01-0.5-Hz filtering, SNR/geometry pruning, with the tutorial's two bad " + ...
            "channels excluded. Full Cedalion TDDR/wavelet preprocessing was not reproduced. SS-DOT uses its " + ...
            "unchanged Research model. The comparator runs the unmodified [NeuroDOT inversion](" + ...
            "https://github.com/WUSTL-ORL/NeuroDOT/blob/734787e22e25da9f49a4d9aae2ebb9cf30dc3a66/" + ...
            "Functions/Reconstruction/Tikhonov_invert_Amat.m), lambda1=0.01/lambda2=0.1, after refitted " + ...
            "sequential SS+drift regression; its native precision/penalty conventions differ. Extinction units " + ...
            "are explicitly converted for spectroscopy_img.");
        paragraph("[Benchmark results](benchmark/summary.json) and [method " + ...
            "comparison](benchmark/method-comparison.csv) use the same baseline-subtracted event average and " + ...
            "4-12-s window for each method. Motor ROIs come from independent SomMot parcel labels, not observed " + ...
            "activation. Method differences can reflect regularization, spatial basis, temporal constraints and " + ...
            "simultaneous versus sequential nuisance removal. Neither method is a gold standard.");

        summary = benchmark.summary;
        diagnostics = summary.diagnostics;
        fitR2 = [summary.fit.rSquaredWithinMeasurement];
        tableBlock({'max |HbO| uM', 'max |HbR| uM', 'Within-channel R2 (760/850)', 'Full SSE', ...
            'Refitted no-brain SSE', 'Brain/scalp penalty ratios (HbO)'}, ...
            {max(abs([summary.hboMinM summary.hboMaxM])) * 1e6, max(abs([summary.hbrMinM summary.hbrMaxM])) * 1e6, ...
            strjoin(compose('%.3f', fitR2), " / "), diagnostics.ablations(1).sse, diagnostics.ablations(2).sse, ...
            compose('%.3g / %.3g', diagnostics.scales(1).penaltyOverComponentScale, ...
            diagnostics.scales(3).penaltyOverComponentScale)});
        holdoutRows = {};
        for j = 1:numel(diagnostics.holdout)
            entry = diagnostics.holdout(j);
            holdoutRows(end + 1, :) = {entry.model, entry.wavelengthNm, entry.rmseOD, entry.rSquaredTrainingMean};
        end
        tableBlock({'Buffered holdout model', 'Wavelength nm', 'RMSE OD', 'R2 vs training channel mean'}, holdoutRows);
        tableBlock({'Condition', 'Hand', 'Hb', 'Side', 'SS-DOT mean uM', 'NeuroDOT mean uM', 'Spatial r'}, ...
            comparisonRows(benchmark));
    end

    function writePublicDataSection()
        heading("Published Gao dataset and exact reproduction", 2);
        if ~isempty(study.publicData)
            tableBlock({'Recording', 'Samples', 'Hz', 'Finite basic OD/Hb', 'ST001 geometry compatible'}, ...
                publicRows(study.publicData));
        end
        paragraph("[Gao dataset DOI](https://doi.org/10.18112/openneuro.ds007420.v1.0.2) provides raw " + ...
            "rest/task/motion data. Required additions remain: registered brain and extracerebral sensitivities " + ...
            "for that actual probe, wavelength/channel/mesh mappings, a documented preprocessing export, " + ...
            "original unilateral reference registration for historical simulation, the original 11-person rest " + ...
            "subset, randomized stimulus sequences/seed and study reference outputs. Public SNIRF, event TSV " + ...
            "and paper durations disagree (10, 1 and 5 s). No duration or hand label is silently corrected. A " + ...
            "bilateral probe definition alone is not a registered forward model.");
        paragraph("Gao [Section 2.7](https://pmc.ncbi.nlm.nih.gov/articles/PMC10203730/) defines CBR from ROI " + ...
            "mean/background SD, t across participants, and LI from contralateral/ipsilateral " + ...
            "above-half-maximum counts. Single-run hand-independent counts or same-run-selected ROI CBR are not " + ...
            "substituted for missing comparable study metrics. Exact historical reproduction remains distinct " + ...
            "from a new, explicitly configured replication.");
        paragraph("NeuroDOT's own visual/language examples are useful additional candidates, but the native " + ...
            "A_AdultV24x28 model is distributed separately via " + ...
            "[NITRC](https://www.nitrc.org/projects/neurodot/). The method comparator above is not a claim that " + ...
            "those native datasets or their full published pipeline have been reproduced.");
    end

    function writeIssuesAndLimits()
        heading("Scientific issues and proposed corrections", 2);
        paragraph("If weak brain recovery recurs in controlled and independent-model tests, review block " + ...
            "scaling and identifiability before interpreting smaller runtime or better optical R2 as progress. " + ...
            "A common global image penalty can suppress brain directions much more than scalp directions; task " + ...
            "signal in the short-channel mean can also be removed by unpenalized nuisance fits. The retained " + ...
            "scale/ablation/ground-truth results distinguish these mechanisms.");
        paragraph("Proposed next correction, requiring separate review: derive and document a physically " + ...
            "consistent brain/scalp scaling or block-regularization objective, including any inverse scaling of " + ...
            "concentrations; then prospectively rerun this fixed benchmark protocol. Separately assess brain " + ...
            "leakage in the actual short channels and whether an independently validated short-channel design " + ...
            "is needed. These would change scientific assumptions, so neither correction is applied here. " + ...
            "Confirm real event meanings, durations and model calibration with the researcher.");
        heading("Execution limits and numerical evidence", 2);
        if ~isempty(study.numericalReference)
            paragraph("Existing dense/optimized reference checks: " + study.numericalReference.passed + ...
                " passed, " + study.numericalReference.failed + " failed, " + ...
                study.numericalReference.incomplete + " incomplete. These certify software behavior only.");
        end
        for k = 1:numel(study.failures)
            failure = study.failures{k};
            paragraph("NOT COMPLETED - " + failure.section + ": " + failure.identifier + " - " + failure.message);
        end
        paragraph("Only available memory is used; a resource failure leaves that section unassessed rather than " + ...
            "reducing resolution. Cancellation retains completed outputs. Original data and vendor reference " + ...
            "code stay outside generated output; outputs/configurations are deliberate retained reports. See " + ...
            "configuration.json, study.json, per-recording CSV/MAT files, benchmark provenance and worker.log " + ...
            "for reproducibility. No commits or pushes are created.");
    end

    function appendFigures()
        try
            images = ssdot.validation.makeStudyPlots(study);
            for image = images(:)'
                html = html + "<figure><img src='" + escapeHtml(image) + "' alt='Scientific diagnostic'></figure>";
            end
        catch exception
            paragraph("Figure generation did not complete: " + string(exception.message) + ...
                ". Numerical outputs remain available.");
        end
    end

    function heading(text, level)
        html = html + "<h" + level + ">" + escapeHtml(text) + "</h" + level + ">";
    end

    function paragraph(text)
        % Markdown-style [label](target) links become anchors after escaping.
        rendered = regexprep(escapeHtml(text), '\[([^\]]+)\]\(([^)]+)\)', '<a href="$2">$1</a>');
        html = html + "<p>" + rendered + "</p>";
    end

    function tableBlock(headers, rows)
        % HTML table of a cell array of rows; nothing for an empty table.
        if isempty(rows)
            return;
        end
        headers = string(headers);
        html = html + "<table><thead><tr>" + strjoin("<th>" + escapeHtml(headers) + "</th>", "") + ...
            "</tr></thead><tbody>";
        for row = 1:size(rows, 1)
            values = strings(1, size(rows, 2));
            for column = 1:size(rows, 2)
                values(column) = formatCell(rows{row, column});
            end
            html = html + "<tr>" + strjoin("<td>" + escapeHtml(values) + "</td>", "") + "</tr>";
        end
        html = html + "</tbody></table>";
    end
end

function text = formatCell(value)
    % Table cell text; numbers that are empty or nonfinite read N/A.
    if isnumeric(value)
        if isempty(value) || any(~isfinite(value))
            text = "N/A";
        else
            text = compose('%.7g', value);
        end
    else
        text = string(value);
    end
end

function document = htmlDocument(body)
    % Complete standalone HTML page around the report body.
    style = "body{font:16px system-ui,sans-serif;max-width:1250px;margin:30px auto;padding:0 24px;" + ...
        "line-height:1.55;color:#202630}h1,h2{color:#163b53}" + ...
        "table{border-collapse:collapse;display:block;overflow:auto;margin:20px 0;font-size:14px}" + ...
        "td,th{border:1px solid #bbc7cf;padding:7px 10px;text-align:left}th{background:#e9f0f5}" + ...
        "figure{margin:24px 0}img{max-width:100%;height:auto}a{color:#075f91}";
    document = "<!doctype html><html><head><meta charset='utf-8'>" + ...
        "<title>SS-DOT scientific validation</title><style>" + style + "</style></head><body>" + body + ...
        "</body></html>";
end

function value = finiteMedian(values)
    % Median of the finite values; NaN when there are none.
    values = values(isfinite(values));
    value = NaN;
    if ~isempty(values)
        value = median(values);
    end
end

function [overview, ablations, holdout, arms] = recordTables(records)
    % One overview row per recording, plus diagnostic rows where diagnostics completed.
    overview = {};
    ablations = {};
    holdout = {};
    arms = {};
    for k = 1:numel(records)
        record = records{k};
        correlations = [record.relationships(strcmp({record.relationships.region}, 'AllModeled')).spatialPearsonR];
        brainPercent = sum([record.components(1:2).percentOfObservedNorm]);
        fitR2 = [record.fit.rSquaredWithinMeasurement];
        mapTable = readtable(fullfile(record.folder, 'map-statistics.csv'), 'TextType', 'string');
        selected = mapTable.scope == "Modeled";
        clipped = sum(mapTable.clippedBelow(selected) + mapTable.clippedAbove(selected));
        overview(end + 1, :) = {record.name, max(abs([record.hboMinM record.hboMaxM])) * 1e6, ...
            max(abs([record.hbrMinM record.hbrMaxM])) * 1e6, ...
            strjoin(compose('%.3f', correlations), " / "), strjoin(compose('%.3f', fitR2), " / "), ...
            brainPercent, record.nanInf, clipped}; %#ok<AGROW>
        if ~isfield(record, 'diagnostics')
            continue;
        end

        diagnostics = record.diagnostics;
        fullSse = diagnostics.ablations(1).sse;
        noBrainSse = diagnostics.ablations(2).sse;
        ablations(end + 1, :) = {record.name, fullSse, noBrainSse, 100 * (noBrainSse - fullSse) / noBrainSse, ...
            diagnostics.conditioning.regularizedImageConditionUpperBound}; %#ok<AGROW>
        for j = 1:numel(diagnostics.holdout)
            entry = diagnostics.holdout(j);
            holdout(end + 1, :) = {record.name, entry.model, entry.wavelengthNm, entry.rmseOD, ...
                entry.rSquaredTrainingMean, entry.targetPairs}; %#ok<AGROW>
        end
        for j = 1:numel(diagnostics.regularization)
            arm = diagnostics.regularization(j);
            arms(end + 1, :) = {record.name, arm.alpha, arm.baseline, arm.imagePenalty, arm.hboMaxAbsM * 1e6, ...
                arm.hbrMaxAbsM * 1e6}; %#ok<AGROW>
        end
    end
end

function rows = referenceComparisonRows(records)
    % One table row per NeuroDOT comparison row of every recording that has one.
    rows = {};
    for k = 1:numel(records)
        record = records{k};
        if ~isfield(record, 'referenceComparison')
            continue;
        end
        for comparison = record.referenceComparison.rows(:)'
            rows(end + 1, :) = {record.name, comparison.conditionName, comparison.chromophore, ...
                comparison.hemisphere, comparison.ssdotMeanM * 1e6, comparison.neurodotMeanM * 1e6, ...
                comparison.spatialPearsonR}; %#ok<AGROW>
        end
    end
end

function rows = scenarioRows(results)
    % Per-scenario summary; medians cover the positive-source rows only.
    rows = {};
    for name = unique(string({results.scenario}), 'stable')
        scenario = results(string({results.scenario}) == name);
        positive = ~[scenario.negativeControl];
        rows(end + 1, :) = {name, numel(scenario), sum([scenario.criteriaPassed]), ...
            finiteMedian([scenario(positive).roiMeanAmplitudeRatio]), ...
            finiteMedian([scenario(positive).localizationErrorMm]), ...
            finiteMedian([scenario(positive).spatialPearsonR]), max([scenario.falsePositiveFraction])}; %#ok<AGROW>
    end
end

function rows = comparisonRows(benchmark)
    % Benchmark method-comparison rows in report units.
    rows = {};
    if ~isfield(benchmark, 'comparison')
        return;
    end
    for comparison = benchmark.comparison(:)'
        rows(end + 1, :) = {comparison.conditionName, comparison.hand, comparison.chromophore, ...
            comparison.hemisphere, comparison.ssdotMeanM * 1e6, comparison.neurodotMeanM * 1e6, ...
            comparison.spatialPearsonR}; %#ok<AGROW>
    end
end

function rows = publicRows(public)
    % One table row per audited public recording.
    rows = {};
    for recording = public.recordings(:)'
        rows(end + 1, :) = {recording.name, recording.samples, recording.sampleRate, recording.basicFinite, ...
            recording.st001GeometryCompatible}; %#ok<AGROW>
    end
end

function text = escapeHtml(text)
    % Escape the characters that are markup in HTML text and attributes.
    text = string(text);
    text = replace(text, "&", "&amp;");
    text = replace(text, "<", "&lt;");
    text = replace(text, ">", "&gt;");
    text = replace(text, "'", "&#39;");
end

function writeText(file, text)
    % Write text to a UTF-8 file.
    fileId = fopen(file, 'w', 'n', 'UTF-8');
    assert(fileId >= 0);
    cleanup = onCleanup(@() fclose(fileId));
    fprintf(fileId, '%s', text);
end
