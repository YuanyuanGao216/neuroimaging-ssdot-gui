function stats = mapStatistics(result, vertices, ras, hemisphere, modeled, names)
    %MAPSTATISTICS Per-hemisphere distribution, extrema and clipping of each map.
    % Modeled covers the sensitivity mask only; FullMesh includes zero padding.
    colorLimit = 1e-9; % fixed GUI color range, M
    rows = {};
    for condition = 1:size(result.hbo, 2)
        for chromophore = ["HbO", "HbR"]
            mapValues = result.(lower(chromophore))(:, condition);
            for scope = ["Modeled", "FullMesh"]
                for side = ["Left", "Right"]
                    index = find(hemisphere == side & (scope == "FullMesh" | modeled));
                    x = mapValues(index);
                    [lowest, iMin] = min(x);
                    [highest, iMax] = max(x);
                    [~, iPeak] = max(abs(x));
                    p = ssdot.validation.percentiles(x, [1 5 25 50 75 95 99]);
                    minVertex = index(iMin);
                    maxVertex = index(iMax);
                    peak = index(iPeak);
                    rows{end + 1} = struct('condition', condition, 'conditionName', string(names{condition}), ...
                        'chromophore', chromophore, 'scope', scope, 'hemisphere', side, 'nVertices', numel(index), ...
                        'minM', lowest, 'maxM', highest, 'meanM', mean(x), 'stdM', std(x), ...
                        'p01M', p(1), 'p05M', p(2), 'p25M', p(3), 'p50M', p(4), ...
                        'p75M', p(5), 'p95M', p(6), 'p99M', p(7), ...
                        'rmsM', sqrt(mean(x.^2)), 'nanCount', sum(isnan(x)), 'infCount', sum(isinf(x)), ...
                        'clippedBelow', sum(x < -colorLimit), 'clippedAbove', sum(x > colorLimit), ...
                        'maxPercentOfColorLimit', 100 * max(abs(x)) / colorLimit, ...
                        'minVertex', minVertex, 'maxVertex', maxVertex, 'absolutePeakVertex', peak, ...
                        'minNative1', vertices(minVertex, 1), 'minNative2', vertices(minVertex, 2), ...
                        'minNative3', vertices(minVertex, 3), ...
                        'maxNative1', vertices(maxVertex, 1), 'maxNative2', vertices(maxVertex, 2), ...
                        'maxNative3', vertices(maxVertex, 3), ...
                        'peakNative1', vertices(peak, 1), 'peakNative2', vertices(peak, 2), ...
                        'peakNative3', vertices(peak, 3), ...
                        'peakRasX', ras(peak, 1), 'peakRasY', ras(peak, 2), 'peakRasZ', ras(peak, 3)); %#ok<AGROW>
                end
            end
        end
    end
    stats = struct2table([rows{:}]);
end
