function stats=mapStatistics(result,v,ras,hemi,modeled,names)
    rows={};
    for c=1:size(result.hbo,2)
        for hb=["HbO","HbR"]
            all=result.(lower(hb))(:,c);
            for scope=["Modeled","FullMesh"]
                for side=["Left","Right"]
                    idx=find(hemi==side & (scope=="FullMesh" | modeled)); x=all(idx);
                    [lo,imin]=min(x); [hi,imax]=max(x); [~,ipeak]=max(abs(x));
                    p=ssdot.validation.percentiles(x,[1 5 25 50 75 95 99]); peak=idx(ipeak);
                    row=struct('condition',c,'conditionName',string(names{c}),'chromophore',hb,'scope',scope, ...
                        'hemisphere',side,'nVertices',numel(idx),'minM',lo,'maxM',hi,'meanM',mean(x),'stdM',std(x), ...
                        'p01M',p(1),'p05M',p(2),'p25M',p(3),'p50M',p(4),'p75M',p(5),'p95M',p(6),'p99M',p(7), ...
                        'rmsM',sqrt(mean(x.^2)),'nanCount',sum(isnan(x)),'infCount',sum(isinf(x)), ...
                        'clippedBelow',sum(x<-1e-9),'clippedAbove',sum(x>1e-9),'maxPercentOfColorLimit',100*max(abs(x))/1e-9, ...
                        'minVertex',idx(imin),'maxVertex',idx(imax),'absolutePeakVertex',peak, ...
                        'minNative1',v(idx(imin),1),'minNative2',v(idx(imin),2),'minNative3',v(idx(imin),3), ...
                        'maxNative1',v(idx(imax),1),'maxNative2',v(idx(imax),2),'maxNative3',v(idx(imax),3), ...
                        'peakNative1',v(peak,1),'peakNative2',v(peak,2),'peakNative3',v(peak,3), ...
                        'peakRasX',ras(peak,1),'peakRasY',ras(peak,2),'peakRasZ',ras(peak,3));
                    rows{end+1}=row;
                end
            end
        end
    end
    stats=struct2table([rows{:}]);
end

