function options = defaultOptions()
    %DEFAULTOPTIONS Fixed, disclosed experiments; no automatic parameter tuning.
    externalRoot = environmentOr('SSDOT_VALIDATION_DATA_ROOT', fullfile(tempdir, 'ssdot-scientific-data'));
    publicRoot = environmentOr('SSDOT_PUBLIC_DATA_ROOT', fullfile(tempdir, 'ssdot-public-data-audit'));
    python = environmentOr('SSDOT_VALIDATION_PYTHON', "python");
    outputRoot = environmentOr('SSDOT_VALIDATION_OUTPUT_ROOT', ...
        fullfile(ssdot.app.projectRoot(), 'results', 'validation'));

    options = struct('schemaVersion', 1, 'datasetRoot', fullfile(ssdot.app.projectRoot(), 'ST001'), ...
        'externalDataRoot', externalRoot, 'publicDataRoot', publicRoot, 'pythonExecutable', python, ...
        'st001', true, 'synthetic', true, 'benchmarks', true, 'outputRoot', outputRoot, 'outputFolder', "", ...
        'alphaValues', [0.001 0.01 0.1], 'noiseSeeds', [12 42 77], ...
        'holdoutBlockSeconds', 60, 'holdoutBufferSeconds', 20, 'effectWindowSeconds', [4 12], ...
        'amplitudeTolerance', [0.5 1.5], 'localizationToleranceMm', 15, ...
        'spatialCorrelationThreshold', 0.5, 'falsePositiveThresholdM', 0.1e-6, ...
        'falsePositiveFractionTolerance', 0.05, 'runNumericalReference', true);
end

function value = environmentOr(name, fallback)
    % A nonempty environment variable (as a string), otherwise the fallback unchanged.
    value = string(getenv(name));
    if strlength(value) == 0
        value = fallback;
    end
end
