function validateMeasurementLayout(probe)
    %VALIDATEMEASUREMENTLAYOUT Enforce the two wavelength blocks used by SS-DOT.
    measurementList = probe.measurementList;
    assert(numel(probe.wavelengths) == 2 && mod(size(measurementList, 1), 2) == 0, ...
        'SSDOT:WavelengthCount', 'The model requires two equally sized wavelength blocks.');
    nPairs = size(measurementList, 1)/2;
    assert(all(measurementList(1:nPairs, 4) == 1) && all(measurementList(nPairs+1:end, 4) == 2) && ...
        isequal(measurementList(1:nPairs, 1:2), measurementList(nPairs+1:end, 1:2)), ...
        'SSDOT:ProbeOrdering', 'Expected matching source-detector pairs in wavelength-1 then wavelength-2 order.');
    assert(size(unique(measurementList(1:nPairs, 1:2), 'rows'), 1) == nPairs, ...
        'SSDOT:DuplicateMeasurements', 'Each optical pair must occur once per wavelength.');
    assert(all(isfinite(probe.sourcePositions), 'all') && all(isfinite(probe.detectorPositions), 'all'), ...
        'SSDOT:ProbeGeometry', 'Optode coordinates must be finite.');
end
