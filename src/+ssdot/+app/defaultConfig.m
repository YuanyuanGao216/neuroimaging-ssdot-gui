function config = defaultConfig()
    %DEFAULTCONFIG Full-resolution profile using professor-compatible temporal inputs.
    % sensitivityThreshold is the brain mask threshold; scalpSensitivityThreshold
    % the scalp one (the professor code uses one value, -2, for both).
    % normalizationDamping is the 0.1 factor of the published spatial normalization.
    % mapTimePoint "hboPeak" samples both chromophore maps at the HbO basis peak (professor).
    config = struct("brainSamplingThreshold", 5, "scalpSamplingThreshold", 5, ...
        "brainSigma", 5, "scalpSigma", 5, "spatialRegularization", false, ...
        "normalizationDamping", 0.1, ...
        "sensitivityThreshold", -2, "scalpSensitivityThreshold", -2, "longSeparationThreshold", 7, ...
        "shortSeparationThreshold", 22, "driftOrder", 3, ...
        "temporalRange", [-2 18], "temporalMode", "professorOriginal", ...
        "temporalParameters", [0.1 3 7 0.1 3 7], ...
        "alpha", 1e-2, "beta", 0, "regularization", 1, ...
        "mapTimePoint", "hboPeak", ...
        "device", "cpu");
end
